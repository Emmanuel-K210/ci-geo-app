// Writes supabase/seed.sql from src/geo/ci-geo.json: the reference as upserts,
// so it can be run again after each update of the JSON.
//
//   npm run db:seed
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"

const root = new URL("..", import.meta.url)
const data = JSON.parse(
  readFileSync(new URL("src/geo/ci-geo.json", root), "utf8")
)

const literal = (value) =>
  value === null || value === undefined
    ? "null"
    : typeof value === "string"
      ? `'${value.replace(/'/g, "''")}'`
      : String(value)

function upsert(table, columns, rows) {
  if (!rows.length) return ""
  const values = rows
    .map((row) => `  (${row.map(literal).join(", ")})`)
    .join(",\n")
  const updates = columns
    .slice(1)
    .map((column) => `${column} = excluded.${column}`)
    .join(", ")
  return `insert into public.${table} (${columns.join(", ")}) values\n${values}\non conflict (id) do update set ${updates};\n`
}

const sql = [
  `-- CI-Geo reference ${data.version}, generated by scripts/supabase-seed.mjs.`,
  "begin;",
  "set constraints all deferred;",
  upsert(
    "districts",
    ["id", "nom", "autonome"],
    data.districts.map((d) => [d.id, d.nom, d.autonome])
  ),
  upsert(
    "regions",
    ["id", "nom", "district_id", "chef_lieu_ville_id"],
    data.regions.map((r) => [r.id, r.nom, r.districtId, r.chefLieuVilleId])
  ),
  upsert(
    "villes",
    [
      "id",
      "nom",
      "lat",
      "lon",
      "district_id",
      "region_id",
      "chef_lieu_de",
      "quartiers_complets",
    ],
    data.villes.map((v) => [
      v.id,
      v.nom,
      v.lat,
      v.lon,
      v.districtId,
      v.regionId,
      v.chefLieuDe,
      v.quartiersComplets,
    ])
  ),
  upsert(
    "localites",
    ["id", "nom", "type", "ville_id"],
    data.localites.map((l) => [l.id, l.nom, l.type, l.villeId])
  ),
  upsert(
    "quartiers",
    ["id", "nom", "localite_id", "ville_id"],
    data.quartiers.map((q) => [q.id, q.nom, q.localiteId, q.villeId])
  ),
  "commit;",
  "",
].join("\n")

mkdirSync(new URL("supabase/", root), { recursive: true })
writeFileSync(new URL("supabase/seed.sql", root), sql)
console.log(
  `supabase/seed.sql: ${data.villes.length} villes, ${data.quartiers.length} quartiers`
)
