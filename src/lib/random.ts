export type Rng = () => number

/** A small seeded generator (mulberry32): the same seed gives the same draws. */
export function seededRng(seed: number): Rng {
  let state = seed >>> 0
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

export function hashSeed(text: string): number {
  let hash = 2166136261
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i)
    hash = Math.imul(hash, 16777619)
  }
  return hash >>> 0
}

export const pick = <T>(list: readonly T[], rng: Rng = Math.random): T =>
  list[Math.floor(rng() * list.length)]

export function shuffle<T>(list: readonly T[], rng: Rng = Math.random): T[] {
  const copy = [...list]
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

export const sample = <T>(list: readonly T[], count: number, rng?: Rng) =>
  shuffle(list, rng).slice(0, count)
